from typing import List, Optional
from pydantic import BaseModel, Field


# --- 1. Revenue Trend Schemas ---
class RevenueTrendPoint(BaseModel):
    """Daily revenue and volume roll-up data point."""

    date: str = Field(..., description="Calendar date in ISO format YYYY-MM-DD")
    total_revenue: float = Field(..., description="Gross revenue earned on this date")
    total_orders: int = Field(..., description="Distinct completed orders")
    avg_order_value: float = Field(..., description="Average basket size (revenue / orders)")
    total_quantity: int = Field(..., description="Total items sold")

    model_config = {"from_attributes": True}


class RevenueTrendResponse(BaseModel):
    """Revenue trend time-series response."""

    days: Optional[int] = Field(None, description="Requested trend time window in calendar days (None if all-time)")
    total_revenue: float = Field(..., description="Cumulative revenue across the period")
    total_orders: int = Field(..., description="Cumulative distinct orders")
    points: List[RevenueTrendPoint] = Field(default_factory=list, description="Ordered daily metric series")
    data_as_of: Optional[str] = Field(None, description="Anchor date for lookback window in ISO format YYYY-MM-DD")


# --- 2. Top Products Schemas ---
class TopProductItem(BaseModel):
    """Product performance ranking metric."""

    product_id: int = Field(..., description="Product surrogate key")
    product_name: str = Field(..., description="Display name of the product or SKU")
    category: Optional[str] = Field("General", description="Product category taxonomy")
    total_revenue: float = Field(..., description="Gross revenue generated by product")
    total_units_sold: int = Field(..., description="Cumulative physical units purchased")
    total_orders: int = Field(..., description="Distinct orders containing this product")

    model_config = {"from_attributes": True}


class TopProductsResponse(BaseModel):
    """Ranked top products response."""

    limit: int = Field(..., description="Result count limit applied")
    days: Optional[int] = Field(None, description="Requested trend time window in calendar days")
    products: List[TopProductItem] = Field(default_factory=list, description="Ranked list of top-selling products")
    data_as_of: Optional[str] = Field(None, description="Anchor date for lookback window in ISO format YYYY-MM-DD")


# --- 3. Late Delivery Risk Schemas ---
class DeliveryRiskBreakdownItem(BaseModel):
    """Fulfillment SLA breakdown per delivery status."""

    status_name: str = Field(..., description="Fulfillment status label (Delivered, In Transit, etc.)")
    total_shipments: int = Field(..., description="Number of packages in this status")
    late_shipments: int = Field(..., description="Packages delayed past SLA deadline")
    late_rate_pct: float = Field(..., description="Percentage of delayed shipments (0.0 - 100.0)")

    model_config = {"from_attributes": True}


class LateDeliveryRiskResponse(BaseModel):
    """Logistics fulfillment risk and SLA delivery summary."""

    total_shipments: int = Field(..., description="Total shipments recorded for tenant")
    late_shipments: int = Field(..., description="Total late deliveries exceeding deadline")
    on_time_shipments: int = Field(..., description="Total deliveries meeting or beating SLA")
    late_rate_pct: float = Field(..., description="Overall tenant late delivery percentage")
    avg_shipping_days: float = Field(..., description="Mean transit duration in calendar days")
    days: Optional[int] = Field(None, description="Requested trend time window in calendar days")
    status_breakdown: List[DeliveryRiskBreakdownItem] = Field(
        default_factory=list,
        description="Fulfillment metrics segmented by delivery status",
    )
    data_as_of: Optional[str] = Field(None, description="Anchor date for lookback window in ISO format YYYY-MM-DD")


# --- 4. Discount vs Profit Schemas ---
class DiscountProfitBand(BaseModel):
    """Margin and revenue analytics for a discount bracket."""

    band: str = Field(..., description="Discount range label (e.g. 0%, 1-10%, 11-20%, 21-30%, >30%)")
    total_revenue: float = Field(..., description="Total revenue generated within this discount tier")
    total_discount: float = Field(..., description="Total discount markdown given")
    total_profit: float = Field(..., description="Calculated gross profit contribution")
    profit_margin_pct: float = Field(..., description="Gross profit margin percentage (profit / revenue * 100)")
    order_count: int = Field(..., description="Number of order lines in this tier")

    model_config = {"from_attributes": True}


class DiscountVsProfitResponse(BaseModel):
    """Discount sensitivity and profitability response."""

    overall_profit_margin_pct: float = Field(..., description="Overall portfolio gross margin percentage")
    overall_discount_rate_pct: float = Field(..., description="Aggregate discount as percentage of gross sales")
    days: Optional[int] = Field(None, description="Requested trend time window in calendar days")
    bands: List[DiscountProfitBand] = Field(default_factory=list, description="Performance metrics by discount tier")
    data_as_of: Optional[str] = Field(None, description="Anchor date for lookback window in ISO format YYYY-MM-DD")


# --- 5. Shipping Mode Comparison Schemas ---
class ShippingModeComparisonItem(BaseModel):
    """Comparative performance metrics across logistics carrier channels."""

    mode_name: str = Field(..., description="Shipping channel name (Standard, Express, Next Day, Freight)")
    shipment_count: int = Field(..., description="Total shipments handled through this mode")
    avg_shipping_days: float = Field(..., description="Mean delivery duration in days")
    late_count: int = Field(..., description="Shipments that breached SLA deadline")
    late_rate_pct: float = Field(..., description="Percentage of late shipments for this channel")
    on_time_rate_pct: float = Field(..., description="Percentage of on-time shipments for this channel")

    model_config = {"from_attributes": True}


class ShippingModeComparisonResponse(BaseModel):
    """Comparative logistics channels response."""

    days: Optional[int] = Field(None, description="Requested trend time window in calendar days")
    modes: List[ShippingModeComparisonItem] = Field(
        default_factory=list,
        description="Performance comparison across all shipping modes",
    )
    data_as_of: Optional[str] = Field(None, description="Anchor date for lookback window in ISO format YYYY-MM-DD")


# --- 6. Organization Owner Home Summary Schemas ---
class DashboardSummaryResponse(BaseModel):
    """
    Overview summary metrics for Organization Owner Home page:
    - the 'Data as of' date
    - four figures from the organization's own data:
      1. total revenue in ₹
      2. order count
      3. late-delivery percentage
      4. average order value in ₹
    - the status of the latest submission in plain words (Ready, Processing, Needs attention - please resend)
    """

    data_as_of: Optional[str] = Field(None, description="Anchor date for organization data in YYYY-MM-DD")
    total_revenue: Optional[float] = Field(None, description="Total revenue amount across organization's data")
    order_count: Optional[int] = Field(None, description="Total order volume count")
    late_delivery_percentage: Optional[float] = Field(None, description="Late delivery percentage rate")
    average_order_value: Optional[float] = Field(None, description="Mean order value amount")
    latest_submission_status: Optional[str] = Field(None, description="Status of latest submission in plain words (Ready, Processing, Needs attention - please resend)")
    latest_submission_batch_id: Optional[str] = Field(None, description="Batch ID of latest submission if any")
    has_data: bool = Field(False, description="Flag indicating whether organization has any data")

    model_config = {"from_attributes": True}

