#!/usr/bin/env python3
"""
Helios Data Platform - API Push Simulator Script (Tenants 8, 9, 10)

Simulates an SMB Owner's external ecommerce / ERP system pushing order data
directly into the Helios platform via POST /api/ingest.

REQUIREMENTS:
- Reads API keys securely from scripts/output/api_keys.json (generated by seed_accounts.py).
- Reads synthetic CSV datasets for Tenants 8, 9, and 10 from scripts/output/.
- Chunks records into batches of 500 rows and sends them with the X-Helios-Api-Key header.
- Respects BACKEND_URL environment variable (default: http://localhost:8000).
- Automatically retries failed chunks up to 3 times with exponential backoff.
- Handles rate limiting gracefully if the API responds with HTTP 429 (Retry-After).
- Reports batch IDs, chunk counts, API-acknowledged record counts, and integrity checks.
- STRICT SECURITY: Never logs or prints the raw API key.

Usage:
    python scripts/data/push_via_api.py [--backend-url http://localhost:8000] [--chunk-size 500] [--dry-run]
"""

import argparse
import csv
import json
import logging
import os
import sys
import time
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

import requests

# Setup repository paths
CURRENT_DIR = Path(__file__).resolve().parent
REPO_ROOT = CURRENT_DIR.parent.parent

if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

# Load environment variables
from dotenv import load_dotenv

for env_path in [
    REPO_ROOT / ".env",
    REPO_ROOT / "backend" / ".env",
    Path.cwd() / ".env",
]:
    if env_path.is_file():
        load_dotenv(dotenv_path=env_path, override=False)

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(name)s: %(message)s",
)
logger = logging.getLogger("helios.data.push_via_api")

# Target tenants configured for API push ingestion
TARGET_TENANT_IDS = [8, 9, 10]
DEFAULT_CHUNK_SIZE = 500
MAX_RETRIES = 3


def load_api_keys(api_keys_file: Path) -> Dict[int, Dict[str, Any]]:
    """
    Read scripts/output/api_keys.json and return a mapping of tenant_id -> key metadata.
    Never exposes raw keys in logging.
    """
    if not api_keys_file.is_file():
        raise FileNotFoundError(
            f"API keys file not found at {api_keys_file}. "
            "Please run scripts/seed_accounts.py first to generate test tenant API keys."
        )

    with open(api_keys_file, "r", encoding="utf-8") as f:
        data = json.load(f)

    keys_list = data.get("keys", [])
    key_map: Dict[int, Dict[str, Any]] = {}

    for k in keys_list:
        t_id = k.get("tenant_id") or k.get("tenant_index")
        if t_id in TARGET_TENANT_IDS:
            key_map[int(t_id)] = k

    return key_map


def read_tenant_csv_records(csv_path: Path) -> List[Dict[str, Any]]:
    """Read a tenant's order CSV file into a list of row dictionaries."""
    if not csv_path.is_file():
        raise FileNotFoundError(
            f"Source CSV file not found at {csv_path}. "
            "Please run scripts/data/generate_synthetic_tenants.py first."
        )

    records: List[Dict[str, Any]] = []
    with open(csv_path, "r", encoding="utf-8", errors="replace") as f:
        reader = csv.DictReader(f)
        for row in reader:
            # Preserve raw field mapping for schema inference
            records.append(dict(row))

    return records


def push_chunk_with_retry(
    url: str,
    api_key: str,
    chunk: List[Dict[str, Any]],
    chunk_idx: int,
    total_chunks: int,
    max_retries: int = MAX_RETRIES,
    base_backoff: float = 1.0,
    dry_run: bool = False,
) -> Tuple[bool, Optional[str], int, Optional[str]]:
    """
    Post a single chunk of records to /api/ingest with retry and rate-limiting logic.
    Never prints or logs the raw API key.
    
    Returns:
        (success, batch_id, records_received, error_message)
    """
    if dry_run:
        # Dry run simulation mode
        simulated_batch_id = f"simulated-batch-{chunk_idx + 1:04d}"
        return True, simulated_batch_id, len(chunk), None

    headers = {
        "X-Helios-Api-Key": api_key,
        "Content-Type": "application/json",
    }
    payload = {"records": chunk}

    attempts = 0
    while attempts < max_retries:
        try:
            resp = requests.post(url, json=payload, headers=headers, timeout=45)

            # 1. Rate limiting (HTTP 429) - Back off and retry without exhausting network attempts
            if resp.status_code == 429:
                retry_after_hdr = resp.headers.get("Retry-After")
                try:
                    wait_sec = float(retry_after_hdr) if retry_after_hdr else 5.0
                except (ValueError, TypeError):
                    wait_sec = 5.0
                logger.warning(
                    "Rate limit reached (HTTP 429) for chunk %d/%d. Waiting %.1fs (Retry-After)...",
                    chunk_idx + 1,
                    total_chunks,
                    wait_sec,
                )
                time.sleep(wait_sec)
                continue

            # 2. Success (HTTP 201 Created or 200 OK)
            if resp.status_code in (200, 201):
                try:
                    resp_data = resp.json()
                    batch_id = str(resp_data.get("batch_id", "unknown"))
                    records_received = int(resp_data.get("records_received", len(chunk)))
                    return True, batch_id, records_received, None
                except Exception as parse_err:
                    return True, f"parsed-ok-{chunk_idx}", len(chunk), None

            # 3. Server errors (HTTP 5xx) - Exponential backoff retry
            if resp.status_code >= 500:
                attempts += 1
                backoff = base_backoff * (2 ** (attempts - 1))
                logger.warning(
                    "Server error HTTP %d on chunk %d/%d. Retry %d/%d in %.1fs...",
                    resp.status_code,
                    chunk_idx + 1,
                    total_chunks,
                    attempts,
                    max_retries,
                    backoff,
                )
                time.sleep(backoff)
                continue

            # 4. Client errors (HTTP 4xx non-429) - Fatal chunk failure
            err_msg = f"HTTP {resp.status_code}: {resp.text[:200]}"
            logger.error("Client error on chunk %d/%d: %s", chunk_idx + 1, total_chunks, err_msg)
            return False, None, 0, err_msg

        except requests.exceptions.RequestException as exc:
            attempts += 1
            backoff = base_backoff * (2 ** (attempts - 1))
            logger.warning(
                "Network exception '%s' on chunk %d/%d. Retry %d/%d in %.1fs...",
                exc,
                chunk_idx + 1,
                total_chunks,
                attempts,
                max_retries,
                backoff,
            )
            time.sleep(backoff)

    return False, None, 0, f"Exceeded maximum retries ({max_retries})"


def push_tenant_data(
    tenant_id: int,
    key_info: Dict[str, Any],
    csv_path: Path,
    ingest_url: str,
    chunk_size: int = DEFAULT_CHUNK_SIZE,
    dry_run: bool = False,
) -> Dict[str, Any]:
    """
    Push all rows of a tenant's synthetic dataset in chunks to the ingestion API.
    Returns tenant summary report metrics.
    """
    business_name = key_info.get("business_name", f"Tenant {tenant_id}")
    masked_key = key_info.get("masked_key", "helios_live_••••")
    raw_api_key = key_info["api_key"]

    logger.info("Processing Tenant %d: '%s' (Key: %s)...", tenant_id, business_name, masked_key)

    records = read_tenant_csv_records(csv_path)
    file_row_count = len(records)

    chunks = [records[i : i + chunk_size] for i in range(0, file_row_count, chunk_size)]
    total_chunks = len(chunks)

    logger.info(
        "Tenant %d: loaded %d rows from %s. Sending in %d chunks (chunk_size=%d)...",
        tenant_id,
        file_row_count,
        csv_path.name,
        total_chunks,
        chunk_size,
    )

    batch_ids: List[str] = []
    total_api_records_received = 0
    successful_chunks = 0
    failed_chunks = 0

    for idx, chunk in enumerate(chunks):
        success, batch_id, received_cnt, err_msg = push_chunk_with_retry(
            url=ingest_url,
            api_key=raw_api_key,
            chunk=chunk,
            chunk_idx=idx,
            total_chunks=total_chunks,
            dry_run=dry_run,
        )

        if success and batch_id:
            successful_chunks += 1
            total_api_records_received += received_cnt
            batch_ids.append(batch_id)
            logger.info(
                "  Chunk %d/%d sent successfully. Batch ID: %s (%d records)",
                idx + 1,
                total_chunks,
                batch_id,
                received_cnt,
            )
        else:
            failed_chunks += 1
            logger.error("  Chunk %d/%d failed: %s", idx + 1, total_chunks, err_msg)

    # Check for row count mismatches
    has_mismatch = (total_api_records_received != file_row_count)

    return {
        "tenant_id": tenant_id,
        "business_name": business_name,
        "masked_key": masked_key,
        "file_name": csv_path.name,
        "file_row_count": file_row_count,
        "total_chunks": total_chunks,
        "successful_chunks": successful_chunks,
        "failed_chunks": failed_chunks,
        "records_received_api": total_api_records_received,
        "has_mismatch": has_mismatch,
        "batch_ids": batch_ids,
    }


def print_tenant_summary(result: Dict[str, Any]) -> None:
    """Print clean formatted report for a single tenant's push results."""
    mismatch_str = (
        f"MISMATCH WARNING! ({result['records_received_api']:,} received vs {result['file_row_count']:,} in file)"
        if result["has_mismatch"]
        else f"MATCH ({result['records_received_api']:,} received == {result['file_row_count']:,} in file)"
    )

    print("\n" + "=" * 80)
    print(f" TENANT {result['tenant_id']}: {result['business_name']} - PUSH REPORT".center(80))
    print("=" * 80)
    print(f"  Masked API Key:       {result['masked_key']}")
    print(f"  Source File:          {result['file_name']} ({result['file_row_count']:,} rows)")
    print(f"  Chunks Sent:          {result['successful_chunks']}/{result['total_chunks']} chunks successfully delivered")
    print(f"  Total API Records:    {result['records_received_api']:,} records confirmed")
    print(f"  Integrity Status:     {mismatch_str}")
    print("  Returned Batch IDs:")
    for b_id in result["batch_ids"][:8]:
        print(f"    - {b_id}")
    if len(result["batch_ids"]) > 8:
        print(f"    ... and {len(result['batch_ids']) - 8} more batch IDs")
    print("-" * 80)


def print_overall_summary_table(results: List[Dict[str, Any]]) -> None:
    """Print overall summary table comparing all API push tenants."""
    headers = ["Tenant", "Business Name", "File Rows", "Chunks", "API Confirmed", "Status"]

    rows = []
    for r in results:
        status_label = "[MISMATCH]" if r["has_mismatch"] else "[OK MATCH]"
        rows.append([
            f"Tenant {r['tenant_id']}",
            r["business_name"],
            f"{r['file_row_count']:,}",
            f"{r['successful_chunks']}/{r['total_chunks']}",
            f"{r['records_received_api']:,}",
            status_label,
        ])

    col_widths = [len(h) for h in headers]
    for row in rows:
        for i, cell in enumerate(row):
            col_widths[i] = max(col_widths[i], len(cell))

    col_widths = [w + 2 for w in col_widths]
    sep_line = "+" + "+".join("-" * w for w in col_widths) + "+"
    header_line = "|" + "|".join(f" {h}".ljust(col_widths[i]) for i, h in enumerate(headers)) + "|"

    print("\n" + "=" * len(sep_line))
    print(" API PUSH INGESTION OVERALL SUMMARY ".center(len(sep_line)))
    print("=" * len(sep_line))
    print(sep_line)
    print(header_line)
    print(sep_line)
    for row in rows:
        line = "|" + "|".join(f" {cell}".ljust(col_widths[i]) for i, cell in enumerate(row)) + "|"
        print(line)
    print(sep_line + "\n")


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Push synthetic tenant datasets (Tenants 8, 9, 10) to Helios via POST /api/ingest"
    )
    parser.add_argument(
        "--backend-url",
        type=str,
        default=os.getenv("BACKEND_URL", "http://localhost:8000"),
        help="Base URL of Helios backend (default: $BACKEND_URL or http://localhost:8000)",
    )
    parser.add_argument(
        "--chunk-size",
        type=int,
        default=DEFAULT_CHUNK_SIZE,
        help=f"Number of rows per API request (default: {DEFAULT_CHUNK_SIZE})",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Simulate chunking and integrity reporting without sending HTTP requests",
    )
    args = parser.parse_args()

    backend_base = args.backend_url.rstrip("/")
    ingest_url = f"{backend_base}/api/ingest"

    logger.info("Initializing API push simulation targeting: %s", ingest_url)
    if args.dry_run:
        logger.info("[DRY RUN MODE ENABLED]: No HTTP network requests will be dispatched.")

    output_dir = REPO_ROOT / "scripts" / "output"
    api_keys_file = output_dir / "api_keys.json"

    # 1. Read API keys
    key_map = load_api_keys(api_keys_file)
    logger.info("Loaded %d API keys for target tenants (Tenants 8, 9, 10).", len(key_map))

    results: List[Dict[str, Any]] = []

    # 2. Iterate tenants and push data
    for tenant_id in TARGET_TENANT_IDS:
        if tenant_id not in key_map:
            logger.error("No API key found in %s for Tenant %d. Skipping.", api_keys_file.name, tenant_id)
            continue

        key_info = key_map[tenant_id]
        csv_path = output_dir / f"tenant_{tenant_id}_orders.csv"

        if not csv_path.is_file():
            logger.error("Dataset %s does not exist. Skipping Tenant %d.", csv_path.name, tenant_id)
            continue

        tenant_result = push_tenant_data(
            tenant_id=tenant_id,
            key_info=key_info,
            csv_path=csv_path,
            ingest_url=ingest_url,
            chunk_size=args.chunk_size,
            dry_run=args.dry_run,
        )
        results.append(tenant_result)
        print_tenant_summary(tenant_result)

    # 3. Overall summary table
    if results:
        print_overall_summary_table(results)


if __name__ == "__main__":
    main()
